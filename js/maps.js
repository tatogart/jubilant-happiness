  function parse(raw) {
    var grid = raw.grid;
    var h = grid.length, w = grid[0].length;
    var cells = new Uint8Array(w * h);
    var floors = new Uint8Array(w * h);
    var ceils = new Uint8Array(w * h);
    var spawns = [], props = [];
    var start = null, exit = null, niches = [];

    for (var y = 0; y < h; y++) {
      var row = grid[y];
      for (var x = 0; x < w; x++) {
        var ch = row[x] || '#';
        var i = y * w + x;
        ceils[i] = raw.ceilTex;
        if (WALL_CHARS[ch]) { cells[i] = WALL_CHARS[ch]; floors[i] = raw.floorTex; continue; }
        floors[i] = raw.floorTex;
        cells[i] = 0;
        var cx = x + 0.5, cy = y + 0.5;
        if (ch === ',') floors[i] = raw.floorTex === 4 ? 4 : (raw.floorTex === 5 ? 5 : 2);
        else if (ch === '@') start = { x: cx, y: cy };
        else if (ch === 'X') {
          exit = { x: cx, y: cy };
          floors[i] = 2;
          props.push({ tex: 'beacon', x: cx, y: cy, z: 0, size: 2.6, additive: true, alpha: 0.85, unfogged: true, tag: 'exit' });
        } else if (SPAWN_CHARS[ch]) spawns.push({ kind: SPAWN_CHARS[ch], x: cx, y: cy });
        else if (ch === 'l') props.push({ tex: raw.floorTex === 4 ? 'pillarWarm' : 'pillar', x: cx, y: cy, z: 0, size: 1.7, blocking: true, radius: 0.3 });
        else if (ch === 't') props.push({ tex: 'terminal', x: cx, y: cy, z: 0, size: 1.1, blocking: true, radius: 0.36 });
        else if (ch === 'n') { props.push({ tex: 'nicheZero', x: cx, y: cy, z: 0.05, size: 1.5, additive: true, alpha: 0.95, unfogged: true, tag: 'niche-zero' }); niches.push({ kind: 'zero', x: cx, y: cy }); }
        else if (ch === 'm') { props.push({ tex: 'nicheEcho', x: cx, y: cy, z: 0.05, size: 1.5, additive: true, alpha: 0.95, unfogged: true, tag: 'niche-echo' }); niches.push({ kind: 'echo', x: cx, y: cy }); }
      }
    }

    return {
      id: raw.id, name: raw.name, subtitle: raw.subtitle,
      w: w, h: h, cells: cells, floors: floors, ceils: ceils,
      floorTex: raw.floorTex, ceilTex: raw.ceilTex,
      fog: raw.fog, fogDist: raw.fogDist, drone: raw.drone,
      start: start, exit: exit, spawns: spawns, props: props, niches: niches,
      finale: raw.id === 5
    };
  }

  var Maps = {
    raw: RAW,
    count: RAW.length,
    meta: RAW.map(function (r) { return { id: r.id, name: r.name, subtitle: r.subtitle }; }),
    load: function (index) { return parse(RAW[index]); },
    solid: function (map, x, y) {
      var cx = x | 0, cy = y | 0;
      if (cx < 0 || cy < 0 || cx >= map.w || cy >= map.h) return true;
      return map.cells[cy * map.w + cx] > 0;
    }
  };

  N.Maps = Maps;
